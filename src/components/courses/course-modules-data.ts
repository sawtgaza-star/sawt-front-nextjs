/* "محاور البرنامج" accordion per course, keyed by the /courses/[id] route id.
   Every module has two video lessons plus the mock's "اختبار قصير" quiz row,
   each with a duration in minutes. */

export type CourseLesson = {
  text: string;
  textKey: string;
  duration: number;
  kind: "video" | "quiz";
};

export type CourseModule = {
  key: string;
  title: string;
  titleKey: string;
  lessons: CourseLesson[];
};

const QUIZ_LESSON: Omit<CourseLesson, "textKey"> & { textKey: string } = {
  text: "اختبار قصير",
  textKey: "crs_lesson_quiz",
  duration: 10,
  kind: "quiz",
};

/* rows: [key, title, [lesson1, minutes], [lesson2, minutes]] — i18n keys
   derive from the stem + module key (hyphens become underscores, matching the
   original crs_module_* keys); lesson keys append _l1 / _l2, and every module
   closes with the shared quiz row. */
function modules(
  stem: string,
  rows: [string, string, [string, number], [string, number]][]
): CourseModule[] {
  return rows.map(([key, title, a, b]) => {
    const titleKey = `${stem}_${key.replace(/-/g, "_")}`;
    return {
      key,
      title,
      titleKey,
      lessons: [
        { text: a[0], textKey: `${titleKey}_l1`, duration: a[1], kind: "video" },
        { text: b[0], textKey: `${titleKey}_l2`, duration: b[1], kind: "video" },
        { ...QUIZ_LESSON },
      ],
    };
  });
}

